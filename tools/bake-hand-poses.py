#!/usr/bin/env python3
"""bake-hand-poses.py <SteamVR dir> > driver/hand_poses.h

Extracts the open-hand (frame 0) and fist (frame 1) reference poses from SteamVR's own resources/anims/
hand_right_poses.glb, mirrors them to the left hand (rule checked against resources/skeletons/vr_glove_*_skeleton.glb)
and prints them as OpenVR VRBoneTransform_t arrays. Run by build.sh; SteamVR's files are not redistributed.
"""
import json, struct, sys


def load(f):
    b = open(f, "rb").read()
    l = struct.unpack("<I", b[12:16])[0]
    j = json.loads(b[20:20 + l])
    off = 20 + l
    bin_ = b[off + 8:off + 8 + struct.unpack("<I", b[off:off + 4])[0]]

    def acc(i):
        a = j["accessors"][i]; v = j["bufferViews"][a["bufferView"]]
        n = {"SCALAR": 1, "VEC3": 3, "VEC4": 4}[a["type"]]
        fl = struct.unpack_from("<%df" % (a["count"] * n), bin_, v.get("byteOffset", 0) + a.get("byteOffset", 0))
        return [fl[k * n:(k + 1) * n] for k in range(a["count"])]
    return j, acc


def pose(j, acc, frame):
    """31 bones (OpenVR order = glb nodes 1..31): [(pos xyz, rot xyzw)], node rest values where not animated."""
    bones = [[list(n.get("translation", [0, 0, 0])), list(n.get("rotation", [0, 0, 0, 1]))] for n in j["nodes"][1:32]]
    an = j["animations"][0]
    for c in an["channels"]:
        s = an["samplers"][c["sampler"]]
        out = acc(s["output"])
        k = c["target"]["node"] - 1
        if 0 <= k < 31:
            bones[k][0 if c["target"]["path"] == "translation" else 1] = list(out[min(frame, len(out) - 1)])
    return bones


SWAP = {2, 6, 11, 16, 21, 26, 27, 28, 29, 30}  # thumb0, metacarpals, aux: left rig differs by an axis swap
ROOT_CHILDREN = {1, 26, 27, 28, 29, 30}          # wrist + aux bones are relative to the root, the rest to their parent


def mirror(bones):
    """Right -> left hand in glTF space. Rule checked against SteamVR's left/right skeleton rest poses; the wrist
    (identity at rest, so the check can't see it) is a plain reflection across the YZ plane."""
    out = []
    for i, (p, q) in enumerate(bones):
        x, y, z, w = q
        r = [w, -z, y, -x] if i in SWAP else [x, -y, -z, w] if i == 1 else [x, y, z, w]
        out.append([[-p[0], p[1], p[2]], r])
    return out


def to_openvr(bones):
    """glTF root frame -> OpenVR root frame: 180 deg about Y for root-relative bones. Matches the OpenVR wrist
    reference values published by ALVR for both hands."""
    out = []
    for i, (p, q) in enumerate(bones):
        if i in ROOT_CHILDREN:
            x, y, z, w = q  # (0,1,0,0)(w=0) * q
            p, q = [-p[0], p[1], -p[2]], [z, w, -x, -y]
        out.append([p, q])
    return out


def check_rule(sv):
    """Fail loudly if SteamVR's own left skeleton disagrees with the mirror rule."""
    jr, _ = load(f"{sv}/resources/skeletons/vr_glove_right_skeleton.glb")
    jl, _ = load(f"{sv}/resources/skeletons/vr_glove_left_skeleton.glb")
    rest = lambda j: [[n.get("translation", [0, 0, 0]), n.get("rotation", [0, 0, 0, 1])] for n in j["nodes"][1:32]]
    for i, ((pa, qa), (pb, qb)) in enumerate(zip(mirror(rest(jr)), rest(jl))):
        same = lambda u, v: all(abs(a - b) < 2e-3 for a, b in zip(u, v)) or all(abs(a + b) < 2e-3 for a, b in zip(u, v))
        if not (same(qa, qb) and all(abs(a - b) < 2e-3 for a, b in zip(pa, pb))):
            sys.exit(f"bake-hand-poses: left/right mirror rule fails at bone {i}: {pa},{qa} vs {pb},{qb}")


def emit(name, bones):
    rows = [f"  {{{{{p[0]:.6f}f, {p[1]:.6f}f, {p[2]:.6f}f, 1.f}}, {{{q[3]:.6f}f, {q[0]:.6f}f, {q[1]:.6f}f, {q[2]:.6f}f}}}}"
            for p, q in bones]
    return f"static const vr::VRBoneTransform_t {name}[31] = {{\n" + ",\n".join(rows) + "\n};\n"


sv = sys.argv[1]
check_rule(sv)
j, acc = load(f"{sv}/resources/anims/hand_right_poses.glb")
openR, fistR = pose(j, acc, 0), pose(j, acc, 1)
print("// Generated by tools/bake-hand-poses.py from SteamVR's hand_right_poses.glb. Do not edit.")
for n, b in (("kOpenRight", to_openvr(openR)), ("kFistRight", to_openvr(fistR)),
             ("kOpenLeft", to_openvr(mirror(openR))), ("kFistLeft", to_openvr(mirror(fistR)))):
    print(emit(n, b))
